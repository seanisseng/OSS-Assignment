"""Compile pinned workflows and preserve Copilot's native Auto in both jobs."""
import hashlib
import inspect
import json
import os
from pathlib import Path
import subprocess


PINNED_HARNESS_SHA256 = 'ef6e2e1d5cab9d4f77fd70d2a203bc1eae8d4b17a83b9a401f8567e44108acec'
ACTION_SHA = '32ecafbc061c9af57e9361942099e381102ae304'
MARKER = '# Native-Auto compatibility: generated by python -m scripts.compile_workflows'


def preserve_native_auto(source, expected_sha256=PINNED_HARNESS_SHA256):
    if hashlib.sha256(source).hexdigest() != expected_sha256:
        raise ValueError('Unexpected Copilot launcher hash; refusing compatibility change')
    needle = b'      role: "main",\n      configuredModel,\n      aliasMap:'
    if source.count(needle) != 1:
        raise ValueError('Expected a unique main-model resolution site')
    replacement = b'      role: "main",\n      configuredModel,\n      preserveAuto: configuredModel === "auto",\n      aliasMap:'
    return source.replace(needle, replacement, 1)


def runtime_source():
    return ('import hashlib, os\nfrom pathlib import Path\n'
            f'PINNED_HARNESS_SHA256 = {PINNED_HARNESS_SHA256!r}\n\n'
            + inspect.getsource(preserve_native_auto)
            + '\nlauncher = Path(os.environ["RUNNER_TEMP"]) / "gh-aw/actions/copilot_harness.cjs"\n'
            + 'if launcher.is_symlink():\n    raise ValueError("Symlink launcher refused")\n'
            + 'launcher.write_bytes(preserve_native_auto(launcher.read_bytes()))\n'
            + 'print("Pinned launcher verified; native Copilot Auto preserved.")\n')


def correction_step(condition=None):
    lines = ['      - name: Preserve native Copilot Auto', '        id: native_auto_launcher']
    if condition:
        lines.append('        if: ' + condition)
    lines.extend(['        run: |', "          python - <<'PY'"])
    lines.extend('          ' + line if line else '' for line in runtime_source().splitlines())
    lines.append('          PY')
    return '\n'.join(lines) + '\n'


def correct_workflow(source):
    first = source.splitlines()[0]
    if not first.startswith('# gh-aw-metadata: '):
        raise ValueError('Missing compiled-workflow metadata')
    if json.loads(first.split(': ', 1)[1]).get('compiler_version') != 'v0.93.5':
        raise ValueError('Compiler version changed; review the compatibility correction')
    if MARKER in source or 'id: native_auto_launcher' in source:
        raise ValueError('Compatibility correction already applied; compile afresh')
    models = [line.split(':', 1)[1].strip() for line in source.splitlines()
              if line.strip().startswith('COPILOT_MODEL:')]
    if models != ['auto', 'auto']:
        raise ValueError('Both analysis and detection must explicitly request native auto')
    main = '      - name: Execute GitHub Copilot CLI\n'
    detection = '      - name: Execute threat detection with AWF\n'
    if source.count(main) != 1 or source.count(detection) != 1:
        raise ValueError('Expected exactly one analysis and one detection execution step')
    tail = source.split(detection, 1)[1].split('        run:', 1)[0]
    conditions = [line.removeprefix('        if: ') for line in tail.splitlines()
                  if line.startswith('        if: ')]
    if len(conditions) != 1:
        raise ValueError('Detection condition changed; refusing an unguarded execution')
    condition = conditions[0]
    source = source.replace(main, correction_step() + main, 1)
    source = source.replace(detection, correction_step(condition) + detection, 1)
    start = source.index(detection)
    source = source[:start] + source[start:].replace(
        '        if: ' + condition,
        '        if: ' + condition + " && steps.native_auto_launcher.outcome == 'success'", 1)
    return source.replace(first + '\n', first + '\n' + MARKER + '\n', 1)


def main():
    compiler = [str(Path('.tools/gh-aw.exe').resolve())] if os.name == 'nt' else ['gh', 'aw']
    version = subprocess.run(compiler + ['--version'], check=True, capture_output=True,
                             text=True, encoding='utf-8').stdout.strip()
    if version != 'gh aw version v0.93.5':
        raise ValueError('Install the reviewed gh-aw v0.93.5 compiler')
    for name in ['clarify', 'smoke']:
        subprocess.run(compiler + ['compile', name, '--action-mode', 'release', '--action-tag',
                                   ACTION_SHA, '--no-check-update'], check=True)
        path = Path('.github/workflows') / (name + '.lock.yml')
        path.write_bytes(correct_workflow(path.read_text(encoding='utf-8')).encode('utf-8'))
        print('Native-Auto compatibility applied to both jobs:', name)


if __name__ == '__main__':
    main()
